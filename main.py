"""Entry program for the news-image-20261126 bounty.

Writes the front-page image for Thursday 26 November 2026 to the
grader's output directory as /output/entry.png.

The image itself ships in this repository as entry.png: a newspaper
front page for Thursday 26 November 2026, built from the day's
reported news. The hero illustration (Tai Po's towers at dusk, with
candles and flowers laid in memory) was generated by the builder
session and carries no text; every headline, the date line and the
captions were drawn with PIL/DejaVu so each word is crisp. The six
main stories are the Wang Fuk Court fire anniversary in Hong Kong,
the leaked Russian war-dead figures, the Chen Jining graft probe in
Shanghai, Abrego Garcia's arrival in Spain, the US tariff plan, and
the World Chess Championship, plus a ticker with six more items.

This program only copies the shipped file after checking it is a
real PNG inside the competition limits (at most 1 MiB, at most
1024x1024). Standard library only, no network, deterministic: the
same bytes go out on every run.
"""

import hashlib
import os
import shutil
import struct
from pathlib import Path

IMAGE_NAME = "entry.png"
MAX_BYTES = 1_048_576
MAX_SIDE = 1024
PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"


def check_png(path: Path) -> int:
    """Validate path as a PNG inside the limits; return its size."""
    blob = path.read_bytes()
    if blob[:8] != PNG_SIGNATURE:
        raise ValueError(f"not a PNG file: {path}")
    if blob[12:16] != b"IHDR":
        raise ValueError(f"not a PNG file (bad IHDR): {path}")
    if len(blob) > MAX_BYTES:
        raise ValueError(f"image too large: {len(blob)} > {MAX_BYTES} bytes")
    # IHDR width/height sit at bytes 16..24 of the file.
    width, height = struct.unpack(">II", blob[16:24])
    if width > MAX_SIDE or height > MAX_SIDE:
        raise ValueError(f"image too big: {width}x{height} > {MAX_SIDE}x{MAX_SIDE}")
    return len(blob)


def main() -> None:
    """Copy the shipped front page into the output directory."""
    here = Path(__file__).resolve().parent
    source = here / IMAGE_NAME
    if not source.is_file():
        raise FileNotFoundError(f"missing shipped image: {source}")
    size = check_png(source)
    out_dir = Path(os.environ.get("MAKEFUN_OUTPUT_DIR", "/output"))
    out_dir.mkdir(parents=True, exist_ok=True)
    target = out_dir / IMAGE_NAME
    shutil.copyfile(source, target)
    digest = hashlib.sha256(source.read_bytes()).hexdigest()
    if hashlib.sha256(target.read_bytes()).hexdigest() != digest:
        raise ValueError(f"copy mismatch: {target}")
    print(f"wrote {target} ({size} bytes, sha256 {digest})")


if __name__ == "__main__":
    main()
